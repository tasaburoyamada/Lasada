def build_symbol32_sreg(out_path):
    """
    Builds zero-copy memory-mapped Symbol32 Registry (.sreg) binary
    with 64-byte alignment containing Asian-Priority Symbol ranges.
    """
    # Header: Magic "SREG", Version 1, SymbolCount 39168
    magic = b"SREG"
    version = 1
    symbol_count = 39168
    
    header = struct.pack("<4sII", magic, version, symbol_count)
    # Align header to 64 bytes
    header += b"\x00" * (64 - len(header))
    
    # Tables: TypeTable (uint8), FeatureTable (uint64), UnicodeTable (uint32)
    type_table = bytes([0] * symbol_count) # SYMBOL_TEXT
    feature_table = bytes([0] * (symbol_count * 8)) # 64-bit Bitfield
    unicode_table = bytearray(symbol_count * 4)
    
    for i in range(symbol_count):
        struct.pack_into("<I", unicode_table, i * 4, i)
        
    payload = type_table + feature_table + bytes(unicode_table)
    # Align payload to 64-byte boundary
    pad_len = (64 - (len(payload) % 64)) % 64
    payload += b"\x00" * pad_len
    
    with open(out_path, "wb") as f:
        f.write(header + payload)
        
    return len(header + payload)

